import streamlit as st
import pandas as pd
import numpy as np
import plotly.graph_objects as go

from sklearn.preprocessing import StandardScaler, PolynomialFeatures
from sklearn.linear_model import LinearRegression
from sklearn.metrics import r2_score


# --------------------------------------------------
# 기본 설정
# --------------------------------------------------

st.set_page_config(
    page_title="서울 연평균기온 다항회귀 분석",
    layout="wide"
)

st.title("서울 연평균기온 다항회귀 분석")


# --------------------------------------------------
# 데이터 불러오기
# --------------------------------------------------

URL = "https://raw.githubusercontent.com/greatsong/modudata/refs/heads/main/data/seoul_daily.csv"

try:
    df = pd.read_csv(URL)
except Exception as e:
    st.error("데이터를 불러오는 중 오류가 발생했습니다.")
    st.exception(e)
    st.stop()


# --------------------------------------------------
# 데이터 전처리
# --------------------------------------------------

df["날짜"] = pd.to_datetime(
    df["날짜"],
    errors="coerce"
)

df["평균기온"] = pd.to_numeric(
    df["평균기온"],
    errors="coerce"
)

df["연도"] = df["날짜"].dt.year


# --------------------------------------------------
# 전체 기록 기간
# --------------------------------------------------

유효날짜 = df["날짜"].dropna()

if len(유효날짜) == 0:
    st.error("유효한 날짜 데이터가 없습니다.")
    st.stop()

기록시작 = 유효날짜.min()
기록종료 = 유효날짜.max()


# --------------------------------------------------
# 데이터 기본 정보
# --------------------------------------------------

st.header("1. 데이터 기본 정보")

col1, col2, col3, col4 = st.columns(4)

with col1:
    st.metric(
        "전체 데이터 수",
        f"{len(df):,}"
    )

with col2:
    st.metric(
        "평균기온 결측치",
        f"{df['평균기온'].isna().sum():,}"
    )

with col3:
    st.metric(
        "기록 시작",
        기록시작.strftime("%Y-%m-%d")
    )

with col4:
    st.metric(
        "기록 종료",
        기록종료.strftime("%Y-%m-%d")
    )


# --------------------------------------------------
# 모든 연도 만들기
# --------------------------------------------------

모든연도 = pd.Index(
    range(
        기록시작.year,
        기록종료.year + 1
    ),
    name="연도"
)


# --------------------------------------------------
# 연도별 유효 날짜 수
# --------------------------------------------------

연도별유효날짜 = (
    df[
        df["날짜"].notna()
        & df["평균기온"].notna()
    ]
    .groupby("연도")
    .size()
    .reindex(
        모든연도,
        fill_value=0
    )
)

연도별유효날짜표 = (
    연도별유효날짜
    .reset_index(
        name="유효날짜수"
    )
)


st.header("2. 연도별 유효 날짜")

st.dataframe(
    연도별유효날짜표,
    use_container_width=True,
    hide_index=True
)


# --------------------------------------------------
# 분석에 사용할 연도
# --------------------------------------------------

# 평균기온이 350일 이상 있는 연도만 사용

분석가능연도 = 연도별유효날짜[
    연도별유효날짜 >= 350
].index


제외연도 = 연도별유효날짜[
    연도별유효날짜 < 350
]


st.write(
    f"평균기온이 350일 이상 있는 "
    f"**{len(분석가능연도):,}개 연도**를 분석에 사용합니다."
)

if len(제외연도) > 0:
    st.subheader("분석에서 제외된 연도")

    st.dataframe(
        제외연도.reset_index(
            name="유효날짜수"
        ),
        use_container_width=True,
        hide_index=True
    )


# --------------------------------------------------
# 연도별 평균기온 계산
# --------------------------------------------------

분석자료 = df[
    df["연도"].isin(분석가능연도)
    & df["평균기온"].notna()
].copy()


연도별평균기온 = (
    분석자료
    .groupby("연도")
    .agg(
        평균기온=("평균기온", "mean"),
        사용날짜수=("평균기온", "count")
    )
    .reset_index()
)


# --------------------------------------------------
# 학습용 / 평가용 데이터 나누기
# --------------------------------------------------

학습자료 = 연도별평균기온[
    연도별평균기온["연도"] <= 2004
].copy()


평가자료 = 연도별평균기온[
    연도별평균기온["연도"] >= 2005
].copy()


if len(학습자료) == 0:
    st.error("2004년까지의 학습용 데이터가 없습니다.")
    st.stop()


if len(평가자료) == 0:
    st.error("2005년 이후의 평가용 데이터가 없습니다.")
    st.stop()


st.header("3. 학습용 데이터와 평가용 데이터")

col1, col2 = st.columns(2)

with col1:
    st.metric(
        "학습용 연도",
        f"{학습자료['연도'].min()} ~ "
        f"{학습자료['연도'].max()}"
    )

with col2:
    st.metric(
        "평가용 연도",
        f"{평가자료['연도'].min()} ~ "
        f"{평가자료['연도'].max()}"
    )


# --------------------------------------------------
# 연도를 계산하기 편한 값으로 바꾸기
# --------------------------------------------------
# 학습 데이터의 평균과 표준편차를 이용합니다.
# 평가 데이터에는 학습 데이터에서 구한 기준을 그대로 사용합니다.

학습X원래 = 학습자료[
    ["연도"]
].values

평가X원래 = 평가자료[
    ["연도"]
].values


scaler = StandardScaler()

학습X = scaler.fit_transform(
    학습X원래
)

평가X = scaler.transform(
    평가X원래
)


# --------------------------------------------------
# 1차, 2차, 3차, 9차 다항회귀
# --------------------------------------------------

차수목록 = [1, 2, 3, 9]

모델결과 = {}

for 차수 in 차수목록:

    # 학습용 데이터에 맞춰 다항식 형태를 만듭니다.
    poly = PolynomialFeatures(
        degree=차수,
        include_bias=False
    )

    학습X다항 = poly.fit_transform(
        학습X
    )

    # 평가용 데이터에는 학습 때 정한 방식을 그대로 적용
    평가X다항 = poly.transform(
        평가X
    )

    # 회귀 모델 학습
    model = LinearRegression()

    model.fit(
        학습X다항,
        학습자료["평균기온"].values
    )

    # 평가용 데이터 예측
    평가예측 = model.predict(
        평가X다항
    )

    # 평가용 R²
    r2 = r2_score(
        평가자료["평균기온"].values,
        평가예측
    )

    # 2050년 변환
    X2050원래 = np.array(
        [[2050]]
    )

    X2050 = scaler.transform(
        X2050원래
    )

    X2050다항 = poly.transform(
        X2050
    )

    예측2050 = model.predict(
        X2050다항
    )[0]

    모델결과[차수] = {
        "poly": poly,
        "model": model,
        "r2": r2,
        "예측2050": 예측2050
    }


# --------------------------------------------------
# 평가 결과 표
# --------------------------------------------------

st.header("4. 모델 성능 비교")

결과표 = pd.DataFrame({
    "모델": [
        "1차 다항회귀",
        "2차 다항회귀",
        "3차 다항회귀",
        "9차 다항회귀"
    ],
    "평가용 R²": [
        모델결과[1]["r2"],
        모델결과[2]["r2"],
        모델결과[3]["r2"],
        모델결과[9]["r2"]
    ],
    "2050년 예측값 (℃)": [
        모델결과[1]["예측2050"],
        모델결과[2]["예측2050"],
        모델결과[3]["예측2050"],
        모델결과[9]["예측2050"]
    ]
})


결과표["평가용 R²"] = 결과표[
    "평가용 R²"
].round(4)

결과표["2050년 예측값 (℃)"] = 결과표[
    "2050년 예측값 (℃)"
].round(2)


st.dataframe(
    결과표,
    use_container_width=True,
    hide_index=True
)


# --------------------------------------------------
# 그래프용 데이터
# --------------------------------------------------

그래프시작연도 = int(
    연도별평균기온["연도"].min()
)

그래프종료연도 = 2050


그래프연도 = np.arange(
    그래프시작연도,
    그래프종료연도 + 1
).reshape(-1, 1)


# 학습 때 만든 scaler를 그대로 사용
그래프X = scaler.transform(
    그래프연도
)


# --------------------------------------------------
# 그래프
# --------------------------------------------------

st.header("5. 학습용·평가용 데이터와 다항회귀 곡선")

fig = go.Figure()


# --------------------------------------------------
# 학습용 실제 데이터
# --------------------------------------------------

fig.add_trace(
    go.Scatter(
        x=학습자료["연도"],
        y=학습자료["평균기온"],
        mode="markers",
        name="학습용 데이터 (2004년까지)",
        marker=dict(
            size=7
        ),
        customdata=학습자료[
            ["사용날짜수"]
        ],
        hovertemplate=(
            "연도: %{x}<br>"
            "평균기온: %{y:.2f} ℃<br>"
            "사용 날짜 수: %{customdata[0]}일"
            "<extra></extra>"
        )
    )
)


# --------------------------------------------------
# 평가용 실제 데이터
# --------------------------------------------------

fig.add_trace(
    go.Scatter(
        x=평가자료["연도"],
        y=평가자료["평균기온"],
        mode="markers",
        name="평가용 데이터 (2005년부터)",
        marker=dict(
            size=7
        ),
        customdata=평가자료[
            ["사용날짜수"]
        ],
        hovertemplate=(
            "연도: %{x}<br>"
            "평균기온: %{y:.2f} ℃<br>"
            "사용 날짜 수: %{customdata[0]}일"
            "<extra></extra>"
        )
    )
)


# --------------------------------------------------
# 다항회귀 곡선
# --------------------------------------------------

곡선차수별표시 = {
    1: "1차 회귀",
    2: "2차 회귀",
    3: "3차 회귀",
    9: "9차 회귀"
}


for 차수 in 차수목록:

    poly = 모델결과[차수]["poly"]
    model = 모델결과[차수]["model"]

    그래프X다항 = poly.transform(
        그래프X
    )

    그래프예측 = model.predict(
        그래프X다항
    )

    fig.add_trace(
        go.Scatter(
            x=그래프연도.flatten(),
            y=그래프예측,
            mode="lines",
            name=곡선차수별표시[차수],
            line=dict(
                width=3
            ),
            hovertemplate=(
                f"{차수}차 회귀<br>"
                "연도: %{x}<br>"
                "예측 평균기온: %{y:.2f} ℃"
                "<extra></extra>"
            )
        )
    )


# --------------------------------------------------
# 학습용 / 평가용 구분선
# --------------------------------------------------

fig.add_vline(
    x=2004.5,
    line_dash="dash",
    annotation_text="학습 → 평가",
    annotation_position="top"
)


# --------------------------------------------------
# 2050년 예측점
# --------------------------------------------------

for 차수 in 차수목록:

    예측2050 = 모델결과[차수]["예측2050"]

    fig.add_trace(
        go.Scatter(
            x=[2050],
            y=[예측2050],
            mode="markers",
            name=f"{차수}차 2050년 예측",
            marker=dict(
                size=10
            ),
            hovertemplate=(
                f"{차수}차 회귀<br>"
                "2050년 예측: %{y:.2f} ℃"
                "<extra></extra>"
            ),
            showlegend=False
        )
    )


# --------------------------------------------------
# 그래프 설정
# --------------------------------------------------

fig.update_layout(
    xaxis_title="연도",
    yaxis_title="연평균기온 (℃)",
    height=700,
    hovermode="closest",
    legend_title="구분"
)


st.plotly_chart(
    fig,
    use_container_width=True
)


# --------------------------------------------------
# 모델별 설명
# --------------------------------------------------

st.header("6. 결과 해석")

가장높은R2차수 = max(
    차수목록,
    key=lambda x: 모델결과[x]["r2"]
)

st.success(
    f"평가용 데이터에서 R²가 가장 높은 모델은 "
    f"**{가장높은R2차수}차 다항회귀**입니다. "
    f"R²는 {모델결과[가장높은R2차수]['r2']:.4f}입니다."
)


st.write(
    "R²가 높을수록 평가용 데이터의 실제 평균기온 변화를 "
    "더 잘 설명한다고 볼 수 있습니다."
)

st.write(
    "2050년 예측값은 각 모델이 학습한 과거의 관계를 "
    "2050년까지 이어서 계산한 값입니다."
)

st.warning(
    "특히 9차와 같이 차수가 높은 모델은 학습 데이터에 "
    "지나치게 맞춰져 평가 데이터에서는 성능이 떨어질 수 있으므로 "
    "R²와 그래프를 함께 비교하는 것이 중요합니다."
)
