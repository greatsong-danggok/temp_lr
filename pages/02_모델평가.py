import streamlit as st
import pandas as pd
import numpy as np
import plotly.graph_objects as go
from sklearn.linear_model import LinearRegression


# --------------------------------------------------
# 기본 설정
# --------------------------------------------------

st.set_page_config(
    page_title="서울 연평균기온 분석",
    layout="wide"
)

st.title("서울 연평균기온 장기 추세 분석")


# --------------------------------------------------
# 데이터 불러오기
# --------------------------------------------------

URL = "https://raw.githubusercontent.com/greatsong/modudata/refs/heads/main/data/seoul_daily.csv"

try:
    df = pd.read_csv(URL)
except Exception as e:
    st.error("데이터를 불러오는 중 오류가 발생했습니다.")
    st.exception(e)
    st.stop()


# --------------------------------------------------
# 데이터 전처리
# --------------------------------------------------

# 날짜 변환
df["날짜"] = pd.to_datetime(df["날짜"], errors="coerce")

# 평균기온 숫자 변환
df["평균기온"] = pd.to_numeric(df["평균기온"], errors="coerce")

# 연도 만들기
df["연도"] = df["날짜"].dt.year


# --------------------------------------------------
# 기본 데이터 정보
# --------------------------------------------------

st.header("1. 데이터 기본 정보")

col1, col2 = st.columns(2)

with col1:
    st.subheader("열 이름")
    st.write(list(df.columns))

with col2:
    st.subheader("기록 기간")

    유효날짜 = df["날짜"].dropna()

    if len(유효날짜) > 0:
        기록시작 = 유효날짜.min()
        기록종료 = 유효날짜.max()

        st.write(
            f"{기록시작.strftime('%Y-%m-%d')} ~ "
            f"{기록종료.strftime('%Y-%m-%d')}"
        )
    else:
        st.write("날짜 데이터가 없습니다.")
        st.stop()


col1, col2, col3, col4 = st.columns(4)

with col1:
    st.metric("전체 데이터 행 수", f"{len(df):,}")

with col2:
    결측치수 = df["평균기온"].isna().sum()
    st.metric("평균기온 결측치", f"{결측치수:,}")

with col3:
    중복날짜수 = df["날짜"].duplicated().sum()
    st.metric("중복 날짜 수", f"{중복날짜수:,}")

with col4:
    st.metric(
        "기록 연수",
        f"{기록종료.year - 기록시작.year + 1:,}"
    )


# --------------------------------------------------
# 중복 날짜 확인
# --------------------------------------------------

중복날짜 = df[df["날짜"].duplicated(keep=False)].sort_values("날짜")

if len(중복날짜) > 0:
    st.subheader("중복 날짜 확인")
    st.dataframe(
        중복날짜[
            ["날짜", "평균기온", "최저기온", "최고기온"]
        ],
        use_container_width=True
    )
else:
    st.success("중복된 날짜가 없습니다.")


# --------------------------------------------------
# 모든 연도 만들기
# --------------------------------------------------
# 데이터가 하나도 없는 연도도 0일로 표시하기 위해
# 기록 시작 연도부터 기록 종료 연도까지 모든 연도를 먼저 만듭니다.

모든연도 = pd.Index(
    range(기록시작.year, 기록종료.year + 1),
    name="연도"
)


# --------------------------------------------------
# 연도별 유효 날짜 수 계산
# --------------------------------------------------

st.header("2. 연도별 평균기온 자료의 유효 날짜 수")

연도별유효날짜 = (
    df[
        df["날짜"].notna()
        & df["평균기온"].notna()
    ]
    .groupby("연도")
    .size()
    .reindex(모든연도, fill_value=0)
)

연도별유효날짜표 = (
    연도별유효날짜
    .reset_index(name="유효날짜수")
)

st.dataframe(
    연도별유효날짜표,
    use_container_width=True,
    hide_index=True
)


# --------------------------------------------------
# 분석 대상 연도 결정
# --------------------------------------------------

# 평균기온이 350일 이상 있는 연도만 분석에 사용합니다.

분석가능연도 = 연도별유효날짜[
    연도별유효날짜 >= 350
].index

제외연도 = 연도별유효날짜[
    연도별유효날짜 < 350
]


st.header("3. 분석 대상 연도")

st.write(
    f"전체 기록 기간의 {len(모든연도):,}개 연도 중 "
    f"{len(분석가능연도):,}개 연도를 분석에 사용합니다."
)

st.write(
    "평균기온이 유효한 날짜가 350일 미만인 연도는 "
    "연평균기온 계산에서 제외했습니다."
)


if len(제외연도) > 0:
    st.subheader("분석에서 제외된 연도")

    제외표 = (
        제외연도
        .reset_index()
        .rename(columns={"유효날짜수": "유효날짜수"})
    )

    st.dataframe(
        제외표,
        use_container_width=True,
        hide_index=True
    )
else:
    st.success("제외되는 연도가 없습니다.")


# --------------------------------------------------
# 분석용 데이터 만들기
# --------------------------------------------------

분석자료 = df[
    df["연도"].isin(분석가능연도)
    & df["평균기온"].notna()
].copy()


# --------------------------------------------------
# 연도별 평균기온 계산
# --------------------------------------------------

연도별평균기온 = (
    분석자료
    .groupby("연도")
    .agg(
        평균기온=("평균기온", "mean"),
        사용날짜수=("평균기온", "count")
    )
    .reset_index()
)

연도별평균기온["평균기온"] = (
    연도별평균기온["평균기온"].round(2)
)


# --------------------------------------------------
# 연도별 평균기온 표
# --------------------------------------------------

st.subheader("연도별 평균기온")

st.dataframe(
    연도별평균기온,
    use_container_width=True,
    hide_index=True
)


# --------------------------------------------------
# 가장 더운 해 / 가장 추운 해
# --------------------------------------------------

더운해5 = (
    연도별평균기온
    .nlargest(5, "평균기온")
    .sort_values("평균기온", ascending=False)
)

추운해5 = (
    연도별평균기온
    .nsmallest(5, "평균기온")
    .sort_values("평균기온", ascending=True)
)


col1, col2 = st.columns(2)

with col1:
    st.subheader("가장 더운 5개 연도")

    st.dataframe(
        더운해5,
        use_container_width=True,
        hide_index=True
    )

with col2:
    st.subheader("가장 추운 5개 연도")

    st.dataframe(
        추운해5,
        use_container_width=True,
        hide_index=True
    )


# --------------------------------------------------
# 선형회귀 모델
# --------------------------------------------------

X = 연도별평균기온[["연도"]].values
y = 연도별평균기온["평균기온"].values


model = LinearRegression()

model.fit(X, y)


# 기울기와 절편
기울기 = model.coef_[0]
절편 = model.intercept_


# --------------------------------------------------
# 학습 데이터의 R² 계산
# --------------------------------------------------

r2 = model.score(X, y)


# --------------------------------------------------
# 2050년 예측
# --------------------------------------------------

예측2050 = model.predict(
    np.array([[2050]])
)[0]


# --------------------------------------------------
# 회귀식
# --------------------------------------------------

if 절편 >= 0:
    회귀식 = f"y = {기울기:.6f}x + {절편:.2f}"
else:
    회귀식 = f"y = {기울기:.6f}x - {abs(절편):.2f}"


# --------------------------------------------------
# 회귀 분석 결과
# --------------------------------------------------

st.header("4. 선형회귀 분석")

col1, col2, col3, col4 = st.columns(4)

with col1:
    st.metric(
        "기울기",
        f"{기울기:.6f} ℃/년"
    )

with col2:
    st.metric(
        "절편",
        f"{절편:.2f}"
    )

with col3:
    st.metric(
        "학습 데이터 R²",
        f"{r2:.4f}"
    )

with col4:
    st.metric(
        "2050년 예측 평균기온",
        f"{예측2050:.2f} ℃"
    )


st.write(f"**회귀식:** `{회귀식}`")

st.info(
    f"학습 데이터의 R² = {r2:.4f}입니다. "
    "R²는 연도만을 이용한 선형회귀가 "
    "학습에 사용된 연도별 평균기온의 변동을 "
    "얼마나 설명하는지를 나타냅니다."
)


# --------------------------------------------------
# 그래프 데이터
# --------------------------------------------------

마지막학습연도 = int(
    연도별평균기온["연도"].max()
)

첫학습연도 = int(
    연도별평균기온["연도"].min()
)


# 실제 학습 기간의 회귀선
회귀선연도 = np.arange(
    첫학습연도,
    마지막학습연도 + 1
)

회귀선X = 회귀선연도.reshape(-1, 1)

회귀선기온 = model.predict(회귀선X)


# 2050년까지 미래 구간
미래연도 = np.arange(
    마지막학습연도,
    2051
)

미래X = 미래연도.reshape(-1, 1)

미래기온 = model.predict(미래X)


# --------------------------------------------------
# 그래프
# --------------------------------------------------

st.header("5. 연도별 평균기온과 장기 추세")


fig = go.Figure()


# --------------------------------------------------
# 일반 연도 산점도
# --------------------------------------------------

특별연도 = set(
    더운해5["연도"].tolist()
    + 추운해5["연도"].tolist()
)

일반자료 = 연도별평균기온[
    ~연도별평균기온["연도"].isin(특별연도)
]


fig.add_trace(
    go.Scatter(
        x=일반자료["연도"],
        y=일반자료["평균기온"],
        mode="markers",
        name="연평균기온",
        marker=dict(
            size=7
        ),
        customdata=일반자료[
            ["사용날짜수"]
        ],
        hovertemplate=(
            "연도: %{x}<br>"
            "평균기온: %{y:.2f} ℃<br>"
            "사용 날짜 수: %{customdata[0]}일"
            "<extra></extra>"
        )
    )
)


# --------------------------------------------------
# 가장 더운 5개 연도
# --------------------------------------------------

fig.add_trace(
    go.Scatter(
        x=더운해5["연도"],
        y=더운해5["평균기온"],
        mode="markers+text",
        name="가장 더운 5개 연도",
        text=[
            f"{int(x)}년"
            for x in 더운해5["연도"]
        ],
        textposition="top center",
        marker=dict(
            size=11,
            color="red"
        ),
        customdata=더운해5[
            ["사용날짜수"]
        ],
        hovertemplate=(
            "연도: %{x}<br>"
            "평균기온: %{y:.2f} ℃<br>"
            "사용 날짜 수: %{customdata[0]}일"
            "<extra></extra>"
        )
    )
)


# --------------------------------------------------
# 가장 추운 5개 연도
# --------------------------------------------------

fig.add_trace(
    go.Scatter(
        x=추운해5["연도"],
        y=추운해5["평균기온"],
        mode="markers+text",
        name="가장 추운 5개 연도",
        text=[
            f"{int(x)}년"
            for x in 추운해5["연도"]
        ],
        textposition="bottom center",
        marker=dict(
            size=11,
            color="blue"
        ),
        customdata=추운해5[
            ["사용날짜수"]
        ],
        hovertemplate=(
            "연도: %{x}<br>"
            "평균기온: %{y:.2f} ℃<br>"
            "사용 날짜 수: %{customdata[0]}일"
            "<extra></extra>"
        )
    )
)


# --------------------------------------------------
# 실제 학습 기간의 회귀선
# --------------------------------------------------

fig.add_trace(
    go.Scatter(
        x=회귀선연도,
        y=회귀선기온,
        mode="lines",
        name="선형회귀선",
        line=dict(
            width=3
        ),
        hovertemplate=(
            "연도: %{x}<br>"
            "회귀 예측값: %{y:.2f} ℃"
            "<extra></extra>"
        )
    )
)


# --------------------------------------------------
# 마지막 학습연도 이후의 추세 연장
# --------------------------------------------------

fig.add_trace(
    go.Scatter(
        x=미래연도,
        y=미래기온,
        mode="lines",
        name="과거 추세를 연장한 값",
        line=dict(
            width=3,
            dash="dash"
        ),
        hovertemplate=(
            "연도: %{x}<br>"
            "추세 연장값: %{y:.2f} ℃"
            "<extra></extra>"
        )
    )
)


# --------------------------------------------------
# 2050년 예측점
# --------------------------------------------------

fig.add_trace(
    go.Scatter(
        x=[2050],
        y=[예측2050],
        mode="markers+text",
        name="2050년 예측",
        text=[f"2050년: {예측2050:.2f} ℃"],
        textposition="top center",
        marker=dict(
            size=13,
            color="green"
        ),
        hovertemplate=(
            "2050년<br>"
            "예측 평균기온: %{y:.2f} ℃"
            "<extra></extra>"
        )
    )
)


# --------------------------------------------------
# 마지막 학습연도 표시
# --------------------------------------------------

fig.add_vline(
    x=마지막학습연도,
    line_dash="dot",
    annotation_text="학습 데이터 마지막 연도",
    annotation_position="top"
)


# --------------------------------------------------
# 그래프 설명
# --------------------------------------------------

fig.update_layout(
    xaxis_title="연도",
    yaxis_title="연평균기온 (℃)",
    hovermode="closest",
    height=650,
    legend_title="구분"
)


st.plotly_chart(
    fig,
    use_container_width=True
)


# --------------------------------------------------
# 2050년 예측 결과
# --------------------------------------------------

st.header("6. 2050년 예측")

st.write(
    f"학습 데이터의 마지막 연도인 "
    f"**{마지막학습연도}년**까지의 장기 추세를 "
    f"2050년까지 그대로 연장하면,"
)

st.markdown(
    f"## 2050년 예상 연평균기온: {예측2050:.2f} ℃"
)

st.write(
    "이 값은 과거 연도별 평균기온과 연도의 관계를 "
    "직선으로 나타낸 뒤 그 추세를 2050년까지 "
    "연장하여 계산한 값입니다."
)


# --------------------------------------------------
# 최종 요약
# --------------------------------------------------

st.header("7. 분석 요약")

st.write(
    f"- 분석에 사용한 연도: **{첫학습연도}~{마지막학습연도}년**"
)

st.write(
    f"- 연도별 평균기온의 상승/하락 기울기: "
    f"**{기울기:.6f} ℃/년**"
)

st.write(
    f"- 선형회귀식: **{회귀식}**"
)

st.write(
    f"- 학습 데이터의 결정계수(R²): **{r2:.4f}**"
)

st.write(
    f"- 2050년 추세 연장 예측값: "
    f"**{예측2050:.2f} ℃**"
)
